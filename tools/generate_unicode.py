#!/usr/bin/env python3
"""Generate the Unicode categories used by the dependency-free BPE pre-tokenizer."""
import pathlib
import unicodedata


def category(cp):
    c = unicodedata.category(chr(cp))
    if c[0] == 'L':
        return 0
    if c[0] == 'N':
        return 1
    if cp in (9, 10, 11, 12, 13, 0x85) or c[0] == 'Z':
        return 2
    if c[0] == 'M':
        return 4
    return 3


def main():
    rows = []
    start, previous = 0, category(0)
    for cp in range(1, 0x110001):
        current = category(cp) if cp < 0x110000 else -1
        if current != previous:
            if previous != 3:
                rows.append(f'    {{ 0x{start:x}, 0x{cp - 1:x}, {previous} }},')
            start, previous = cp, current
    text = (f'// Generated by tools/generate_unicode.py, Unicode {unicodedata.unidata_version}.\n'
            '// Categories: letter, number, whitespace, other (implicit), mark.\n'
            'static const struct { uint32_t first, last; int kind; } unicode_ranges[] = {\n'
            + '\n'.join(rows) + '\n};\n')
    (pathlib.Path(__file__).resolve().parents[1] / 'src/unicode.h').write_text(text)


if __name__ == '__main__':
    main()
